//go:build unix

package fslib

import "os"

// syncDirAt opens the directory read-only and fsyncs it.
func syncDirAt(path string) error {
	d, err := os.Open(path)
	if err != nil {
		return err
	}
	serr := d.Sync()
	cerr := d.Close()
	if serr != nil {
		return serr
	}
	return cerr
}
